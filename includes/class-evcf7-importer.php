<?php
/**
 * CFDB7 CSV Importer.
 *
 * Parses a CSV exported by the CFDB7 plugin and inserts each row into the
 * cf7_entries + cf7_entry_meta tables.
 *
 * CFDB7 export columns:
 *   Id, Date, Status, Name, Email, Subject, Message [, extra columns …]
 *
 * Mapping applied on import:
 *   Id      → _cfdb7_id  (hidden meta – used for duplicate detection)
 *   Date    → created_at on the entry row
 *   Status  → status column ('read' | 'unread')
 *   Name    → your-name
 *   Email   → your-email
 *   Subject → your-subject
 *   Message → your-message
 *   others  → lower-cased, space→hyphen field name
 *
 * Bugs fixed vs previous version
 * --------------------------------
 * 1. isset() used instead of empty() for the submit-button check –
 *    <button> with no value= attribute posts an empty string; empty('') is
 *    TRUE so the old handler returned immediately without doing anything.
 * 2. SplFileObject used instead of fgetcsv() so UTF-8 / Cyrillic content
 *    is read byte-for-byte without locale-dependent misinterpretation.
 * 3. \r\n normalised to \n inside field values before storing.
 * 4. wp_sanitize_textarea_field (not wp_kses_post) used for message bodies
 *    so HTML entities in spam messages are preserved as text, not stripped
 *    or partially corrupted.
 *
 * @package EVCF7_Plugin
 * @since   1.0.0
 */

if ( ! defined( 'ABSPATH' ) ) { exit; }

class EVCF7_Importer {

	private static $instance = null;

	/**
	 * CFDB7 CSV column label → CF7 tag name.
	 *
	 * @var string[]
	 */
	private static $col_map = array(
		'Name'    => 'your-name',
		'Email'   => 'your-email',
		'Subject' => 'your-subject',
		'Message' => 'your-message',
	);

	public static function instance() {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	private function __construct() {
		add_action( 'admin_init', array( $this, 'handle_post' ) );
	}

	/* -----------------------------------------------------------------------
	 * HTTP handler (admin_init)
	 * -------------------------------------------------------------------- */

	public function handle_post() {
		/*
		 * BUG FIX #1
		 * Use isset() not empty().
		 * A <button type="submit" name="evcf7_import_submit"> with no value=
		 * attribute posts an empty string ''. PHP's empty('') returns TRUE,
		 * so the old empty() check caused the handler to exit immediately
		 * without ever processing the file.
		 */
		if ( ! isset( $_POST['evcf7_import_submit'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Missing -- branch-selection only (is this our form?); nonce verified below via check_admin_referer() before any file is processed.
			return;
		}

		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( esc_html__( 'Permission denied.', 'entryvault-contact-form-7' ) );
		}

		check_admin_referer( 'evcf7_import' );

		/*
		 * Validate file upload.
		 *
		 * Every $_FILES['evcf7_csv'][...] index is checked with isset() before
		 * use (avoids "possibly undefined array index" warnings).
		 *
		 * IMPORTANT: $_FILES['evcf7_csv']['tmp_name'] is a path generated by
		 * PHP's own upload handler (not raw request data), e.g. on Windows:
		 *   C:\xampp\tmp\php3F2A.tmp
		 *
		 * It must NOT be passed through wp_unslash() or sanitize_text_field():
		 *  - wp_unslash() calls stripslashes(), which removes every backslash
		 *    from the string. "C:\xampp\tmp\php3F2A.tmp" becomes
		 *    "C:xampptmpphp3F2A.tmp" — a path that does not exist, so
		 *    is_uploaded_file() returns false and the importer reports
		 *    "No file was uploaded" even though the upload succeeded.
		 *  - sanitize_text_field() has the same backslash-stripping problem
		 *    plus additional whitespace normalisation.
		 *
		 * $_FILES values are populated directly by PHP from the multipart
		 * upload and are never subject to WordPress's addslashes() wrapping
		 * of $_GET/$_POST/$_COOKIE, so wp_unslash() is not needed here at
		 * all. is_uploaded_file() below is the correct and sufficient
		 * security check that this is a genuine PHP-managed upload path.
		 */
		$file_error = isset( $_FILES['evcf7_csv']['error'] ) ? (int) $_FILES['evcf7_csv']['error'] : UPLOAD_ERR_NO_FILE;
		$tmp_name   = isset( $_FILES['evcf7_csv']['tmp_name'] ) ? (string) $_FILES['evcf7_csv']['tmp_name'] : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- PHP-generated upload temp path (not raw request data); wp_unslash()/sanitize_text_field() corrupt Windows paths via stripslashes(). Validated below via is_uploaded_file().

		$upload_ok = (
			'' !== $tmp_name &&
			UPLOAD_ERR_OK === $file_error &&
			is_uploaded_file( $tmp_name )
		);

		if ( ! $upload_ok ) {
			wp_safe_redirect( add_query_arg(
				array( 'page' => 'evcf7-import', 'evcf7_err' => 'no_file' ),
				admin_url( 'admin.php' )
			) );
			exit;
		}

		$original_name = isset( $_FILES['evcf7_csv']['name'] ) ? sanitize_file_name( wp_unslash( $_FILES['evcf7_csv']['name'] ) ) : '';
		$ext           = strtolower( pathinfo( $original_name, PATHINFO_EXTENSION ) );

		if ( 'csv' !== $ext ) {
			wp_safe_redirect( add_query_arg(
				array( 'page' => 'evcf7-import', 'evcf7_err' => 'bad_type' ),
				admin_url( 'admin.php' )
			) );
			exit;
		}

		$form_id = isset( $_POST['evcf7_form_id'] ) ? absint( $_POST['evcf7_form_id'] ) : 0; // phpcs:ignore WordPress.Security.NonceVerification.Missing -- nonce already verified above via check_admin_referer().
		$result  = $this->import_csv( $tmp_name, $form_id );

		wp_safe_redirect( add_query_arg(
			array(
				'page'           => 'evcf7-import',
				'evcf7_imported' => $result['imported'],
				'evcf7_skipped'  => $result['skipped'],
				'evcf7_errors'   => $result['errors'],
			),
			admin_url( 'admin.php' )
		) );
		exit;
	}

	/* -----------------------------------------------------------------------
	 * Core import logic
	 * -------------------------------------------------------------------- */

	/**
	 * Parse a CFDB7 CSV file and insert rows into the database.
	 *
	 * @param string $filepath Absolute server path to the uploaded file.
	 * @param int    $form_id  CF7 form post ID to assign entries to (0 = none).
	 * @return array { imported: int, skipped: int, errors: int }
	 */
	public function import_csv( $filepath, $form_id = 0 ) {
		$imported = 0;
		$skipped  = 0;
		$errors   = 0;

		if ( ! is_readable( $filepath ) ) {
			return compact( 'imported', 'skipped', 'errors' );
		}

		/*
		 * BUG FIX #2
		 * Use SplFileObject instead of fopen() + fgetcsv().
		 * PHP's fgetcsv() relies on the system locale for character width
		 * when the mbstring extension is active (mbstring.func_overload).
		 * This causes multi-byte UTF-8 characters (Cyrillic, Arabic, CJK …)
		 * inside quoted CSV fields to be split at wrong byte boundaries,
		 * producing garbled text or incorrectly terminated rows.
		 * SplFileObject::fgetcsv() is not affected by func_overload and
		 * reads raw bytes, which is exactly what we need for UTF-8 CSV.
		 */
		try {
			$file = new SplFileObject( $filepath, 'r' );
			$file->setFlags( SplFileObject::READ_CSV | SplFileObject::SKIP_EMPTY | SplFileObject::READ_AHEAD );
			$file->setCsvControl( ',', '"', '\\' );
		} catch ( RuntimeException $e ) {
			return compact( 'imported', 'skipped', 'errors' );
		}

		// ── Read & normalise the header row ──────────────────────────────────
		$raw_headers = $file->current();
		$file->next();

		if ( ! is_array( $raw_headers ) || empty( $raw_headers ) ) {
			return compact( 'imported', 'skipped', 'errors' );
		}

		// Strip UTF-8 BOM (EF BB BF) from the very first field.
		$raw_headers[0] = preg_replace( '/^\xEF\xBB\xBF/', '', $raw_headers[0] );

		$headers = array_map( 'trim', $raw_headers );

		// Identify reserved column positions.
		$id_col     = array_search( 'Id',     $headers, true );
		$date_col   = array_search( 'Date',   $headers, true );
		$status_col = array_search( 'Status', $headers, true );

		// Build index of field columns (everything that is not a reserved col).
		$reserved   = array( 'Id', 'Date', 'Status' );
		$field_cols = array(); // col_index => cf7_field_name
		foreach ( $headers as $i => $h ) {
			if ( in_array( $h, $reserved, true ) ) {
				continue;
			}
			$field_cols[ $i ] = isset( self::$col_map[ $h ] )
				? self::$col_map[ $h ]
				: strtolower( str_replace( ' ', '-', $h ) );
		}

		$total_cols = count( $headers );

		// ── Process data rows ─────────────────────────────────────────────────
		while ( $file->valid() ) {
			$row = $file->current();
			$file->next();

			if ( ! is_array( $row ) || empty( array_filter( $row ) ) ) {
				continue;
			}

			// Pad short rows (trailing empty columns stripped by some editors).
			while ( count( $row ) < $total_cols ) {
				$row[] = '';
			}

			// ── Duplicate check ───────────────────────────────────────────────
			$cfdb7_id = ( false !== $id_col && isset( $row[ $id_col ] ) )
				? absint( trim( $row[ $id_col ] ) )
				: 0;

			if ( $cfdb7_id && EVCF7_Database::cfdb7_id_exists( $cfdb7_id ) ) {
				$skipped++;
				continue;
			}

			// ── Date ──────────────────────────────────────────────────────────
			$date = ( false !== $date_col && ! empty( trim( $row[ $date_col ] ) ) )
				? sanitize_text_field( trim( $row[ $date_col ] ) )
				: current_time( 'mysql', true );

			// ── Status ────────────────────────────────────────────────────────
			$raw_status = ( false !== $status_col && ! empty( $row[ $status_col ] ) )
				? strtolower( trim( $row[ $status_col ] ) )
				: 'unread';
			$status = in_array( $raw_status, array( 'read', 'unread' ), true )
				? $raw_status
				: 'unread';

			// ── Fields ────────────────────────────────────────────────────────
			$fields = array();
			foreach ( $field_cols as $idx => $field_name ) {
				$raw_value = isset( $row[ $idx ] ) ? $row[ $idx ] : '';

				/*
				 * BUG FIX #3 + #4
				 * Normalise \r\n → \n so stored text displays correctly.
				 * Use sanitize_textarea_field (not wp_kses_post) so that
				 * HTML inside spam messages (e.g. <a href=https://…>) is
				 * stored as text rather than partially stripped by kses.
				 */
				$raw_value = str_replace( "\r\n", "\n", $raw_value );
				$raw_value = str_replace( "\r",   "\n", $raw_value );

				$fields[ $field_name ] = sanitize_textarea_field( $raw_value );
			}

			// Store the original CFDB7 Id as a hidden meta field.
			if ( $cfdb7_id ) {
				$fields['_cfdb7_id'] = (string) $cfdb7_id;
			}

			// ── Insert ────────────────────────────────────────────────────────
			$entry_id = EVCF7_Database::insert_entry( $form_id, $fields, $status, $date );

			if ( $entry_id ) {
				/**
				 * Fires after a single CFDB7 row has been successfully imported.
				 *
				 * @since 1.0.0
				 * @param int   $entry_id  Newly inserted entry ID.
				 * @param int   $cfdb7_id  Original CFDB7 Id value (0 if absent).
				 * @param array $fields    Stored field data.
				 */
				do_action( 'evcf7_after_cfdb7_import', $entry_id, $cfdb7_id, $fields );
				$imported++;
			} else {
				$errors++;
			}
		}

		unset( $file ); // release file handle

		return compact( 'imported', 'skipped', 'errors' );
	}
}
